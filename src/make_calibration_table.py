"""
LaTeX table for the market-calibrated scope section, generated from the measurement files.

Kept as a generator rather than typed by hand for the same reason as the other tables: a number in
the paper that no script produces is a number that cannot be re-checked. The two sources are
`exp_spread_cfl_cost.json` (the per-instrument CFL cost) and `exp_real_calibration.json` (the
accuracy under real coefficients).

Usage: python src/make_calibration_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parent.parent / "results"
TABDIR = Path(__file__).resolve().parent.parent / "paper" / "tables"


def main() -> int:
    cfl = json.loads((RESULTS / "exp_spread_cfl_cost.json").read_text(encoding="utf-8"))
    baseline = cfl["baseline"]
    per_asset = cfl["per_asset"]

    # Ordered by spread, tightest first, so the reader sees the trend rather than a sorted list.
    rows = sorted(per_asset, key=lambda r: r["eta"])
    base_steps = baseline["n_steps"]

    lines = [
        "% Auto-generated by src/make_calibration_table.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{The explicit grid scheme's time-step requirement under measured liquidity. "
        "$\\eta$ is half the Roll effective spread \\cite{roll1984simple} measured on the causal "
        "minute data, with Corwin--Schultz \\cite{corwin2012simple} as a cross-check. The optimal "
        "control is $u^\\star = -R^{-1}B^\\top P x$ with $R = \\eta I$, and the explicit time step is "
        "CFL-limited by $dt \\le 0.25\\,dx/\\|u^\\star\\|_\\infty$, so a smaller $\\eta$ buys a larger "
        "control and a proportionally smaller step. Everything else is held at the paper's "
        "synthetic values, so the column is a statement about the instrument's liquidity alone. "
        "The ordering is the point: the most liquid instrument pays the largest penalty.}",
        "\\label{tab:calib}",
        "\\small",
        "\\begin{tabular}{l r r r r}",
        "\\toprule",
        " & half-Roll & $\\max|u^\\star|$ & time & vs.\\ synthetic \\\\",
        "instrument & spread $\\eta$ & on grid & steps & calibration \\\\",
        "\\midrule",
        f"synthetic & {baseline['eta']:.2e} & {baseline['max_u']:.1f} & "
        f"{base_steps:,.0f} & $1\\times$ \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(f"{r['asset']} & {r['eta']:.2e} & {r['max_u']:.0f} & "
                     f"{r['n_steps']:,.0f} & ${r['n_steps'] / base_steps:.0f}\\times$ \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    out = TABDIR / "tab_calib.tex"
    TABDIR.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    for r in rows:
        print(f"  {r['asset']:>6} eta={r['eta']:.2e} max|u|={r['max_u']:>6.0f} "
              f"steps={r['n_steps']:>8,.0f} ({r['n_steps'] / base_steps:.0f}x)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
