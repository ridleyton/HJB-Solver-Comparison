"""
LaTeX table for the reconstruction-order sweep, generated from the measurement file.

The paper's control-accuracy claim rests on comparing exactly two reconstructions (multilinear,
order 2, against cubic, order 4). This table generalises it across four polynomial degrees on three
test functions, so the claim stops resting on two points. Generated rather than typed for the usual
reason: a number no script produces cannot be re-checked.

Usage: python src/make_order_table.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

RESULTS = Path(__file__).resolve().parent.parent / "results"
TABDIR = Path(__file__).resolve().parent.parent / "paper" / "tables"

FUNC_LABEL = {"exp": "exp.", "trig": "trig.", "rational": "rational"}


def main() -> int:
    path = RESULTS / "exp_reconstruction_order.json"
    if not path.exists():
        print(f"missing {path}; run exp_reconstruction_order.py first")
        return 1
    d = json.loads(path.read_text(encoding="utf-8"))
    rows = [r for r in d["results"] if not r["machine_exact"] and math.isfinite(r["order"])]
    degrees = sorted({r["degree"] for r in rows})
    funcs = [f for f in ("exp", "trig", "rational")
             if any(r["function"] == f for r in rows)]

    lines = [
        "% Auto-generated by src/make_order_table.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{The gradient-error convergence rate against the reconstruction's polynomial "
        "degree, on a jittered mesh. Each cell is a separate reconstruction of the same nodal "
        "values, and every degree is differentiated by the SAME rule -- central differences on its "
        "own interpolant -- so the only thing varying across a row is the reconstruction. The rate "
        "rises with the degree and the error at fixed mesh falls by four to five orders of "
        "magnitude, which makes the paper's recommendation actionable beyond the two reconstructions "
        "it was originally tested on.}",
        "\\label{tab:order}",
        "\\small",
        "\\begin{tabular}{r " + "r" * len(funcs) + "}",
        "\\toprule",
        "degree & " + " & ".join(FUNC_LABEL[f] for f in funcs) + " \\\\",
        "\\midrule",
    ]
    for deg in degrees:
        cells = []
        for f in funcs:
            hit = [r for r in rows if r["degree"] == deg and r["function"] == f]
            cells.append(f"{hit[0]['order']:.2f}" if hit else "--")
        lines.append(f"{deg} & " + " & ".join(cells) + " \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    out = TABDIR / "tab_order.tex"
    TABDIR.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    for deg in degrees:
        cells = {f: next((r["order"] for r in rows
                          if r["degree"] == deg and r["function"] == f), float("nan"))
                 for f in funcs}
        print(f"  degree {deg}: " + "  ".join(f"{f}={v:.2f}" for f, v in cells.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())