def tab_budget(d) -> None:
    """Fairness check: does more training rescue the PINN at higher dimension?"""
    if not d:
        return
    runs = [r for r in d.get("runs", []) if "value_r2" in r]
    if not runs:
        return
    dims = sorted({r["p"] for r in runs})
    ladder = sorted({(r["epochs"], r["n_collocation"]) for r in runs})
    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Fairness check on the neural solver: accuracy against training budget. "
        "Architecture and learning rate are held fixed while optimisation steps and "
        "collocation points are scaled. A budget artefact would show accuracy recovering "
        "with budget; it does not.}",
        "\\label{tab:budget}",
        "\\small",
        "\\begin{tabular}{rrrrr}",
        "\\toprule",
        "$p$ & epochs & collocation & time (s) & value $R^2$ \\\\",
        "\\midrule",
    ]
    for p in dims:
        for (ep, nc) in ladder:
            sel = [r for r in runs if r["p"] == p and r["epochs"] == ep
                   and r["n_collocation"] == nc]
            if not sel:
                continue
            t = np.mean([r["solve_time_s"] for r in sel])
            r2 = np.mean([r["value_r2"] for r in sel])
            worst = min(r["value_r2"] for r in sel)
            pp = str(p) if (ep, nc) == ladder[0] else ""
            r2s = f"{r2:+.4f}" if len(sel) == 1 else f"{r2:+.4f} (min {worst:+.3f})"
            lines.append(f"{pp} & {ep} & {nc} & {t:.1f} & {r2s} \\\\")
        lines.append("\\midrule")
    if lines[-1] == "\\midrule":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_budget.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_budget.tex")


def tab_main(dim, grid) -> None:
    """The paper's central table: accuracy and cost, fixed-budget and accuracy-matched.

    Consolidates what were three separate tables (a 6-column accuracy table that overflowed a
    single column, a cost table, and a crossover table) into one full-width table. Each row is
    a state dimension; the grid columns use the smallest resolution reaching R^2 >= 0.9999 at
    that dimension, so the two families are compared at equal accuracy.
    """
    if not dim or not grid:
        return
    runs = [r for r in dim["runs"] if r.get("feasible")]
    dims = sorted({r["p"] for r in runs})
    summary = grid.get("summary", {})

    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Accuracy and cost by state dimension, against the closed-form Riccati "
        "solution. The grid columns use $N^\\star$, the smallest resolution reaching value "
        "$R^2 \\ge 0.9999$ at that dimension (found by refinement), so the two families are "
        "compared at equal accuracy rather than equal resolution. PINN columns are a "
        "\\emph{fixed} budget of 6000 epochs and 2048 collocation points; a larger budget "
        "rescues $p=4$ and is discussed in the text. Times are GPU for the PINN and CPU for the "
        "grid scheme. A negative $R^2$ means the learned value function is worse than "
        "predicting the mean, i.e. the solver has failed rather than merely lost accuracy.}",
        "\\label{tab:main}",
        "\\small",
        "\\begin{tabular}{r rr rr rr rr}",
        "\\toprule",
        "& \\multicolumn{4}{c}{grid scheme (accuracy-matched)} "
        "& \\multicolumn{4}{c}{PINN (fixed budget)} \\\\",
        "\\cmidrule(lr){2-5} \\cmidrule(lr){6-9}",
        "$p$ & $N^\\star$ & time (s) & value $R^2$ & ctrl $R^2$ "
        "& time (s) & value $R^2$ & ctrl $R^2$ & sign agr. \\\\",
        "\\midrule",
    ]
    for p in dims:
        g = summary.get(str(p)) or summary.get(p)
        pin = [r for r in runs if r["method"] == "PINN" and r["p"] == p]
        pin_t = _mean_sd([r.get("solve_time_s") for r in pin], 1)
        pin_r2 = _mean_sd([r.get("value_r2") for r in pin], 4)
        pin_cr2 = _mean_sd([r.get("control_r2") for r in pin], 4)
        pin_sa = _mean_sd([r.get("control_sign_agreement") for r in pin], 3)
        if g and g.get("N_star"):
            gt, gr2, ns = f"{g['time_s']:.3f}", f"{g['value_r2']:.5f}", str(g["N_star"])
        else:
            gt, gr2, ns = "--", "--", "--"
        # Control accuracy of the grid scheme at the accuracy-matched resolution.
        grow = [r for r in grid.get("runs", [])
                if r.get("p") == p and r.get("N") == g.get("N_star")] if g else []
        gc = f"{grow[0]['control_r2']:.4f}" if grow and grow[0].get("control_r2") is not None else "--"
        mark = ""
        if pin and g and g.get("N_star"):
            m_r2 = float(np.mean([r["value_r2"] for r in pin]))
            if m_r2 < 0.99:
                mark = "$^{\\ast}$"
