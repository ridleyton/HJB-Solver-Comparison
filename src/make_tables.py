"""
Generate the paper's LaTeX tables from the corrected result files.

Every number in the paper's tables is produced here from `results/*.json`. Nothing is typed
by hand, and no figure is carried over from the audited baseline.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import numpy as np

RESULTS = Path("results")
TABDIR = Path("paper/tables")
METHOD_ORDER = ["Finite Difference", "Policy Iteration", "PINN"]


def _fmt(v, nd=3, pct=False, signed=False):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "--"
    if pct:
        return f"{v*100:+.{nd}f}" if signed else f"{v*100:.{nd}f}"
    return f"{v:+.{nd}f}" if signed else f"{v:.{nd}f}"


def _mean_sd(vals, nd=4):
    v = np.asarray([x for x in vals if x is not None and np.isfinite(x)], dtype=float)
    if v.size == 0:
        return "--"
    if v.size == 1:
        return f"{v[0]:.{nd}f}"
    return f"{v.mean():.{nd}f} $\\pm$ {v.std(ddof=1):.{nd}f}"


def load(name: str):
    p = RESULTS / name
    if not p.exists():
        return None
    return json.loads(p.read_text())


