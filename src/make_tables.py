def tab_ood(d) -> None:
    """Out-of-domain table, trimmed to five instruments spanning the price range."""
    if not d:
        return
    conds = d.get("conditions", {})
    un = conds.get("unscaled_raw_price", [])
    rs = conds.get("price_rescaled_to_train_domain", [])
    if not un:
        return
    assets_all = [r["asset"] for r in un[0]["per_asset"]]
    # Keep five evenly spaced instruments so the table still spans $42 to $536.
    keep = [0, 2, 4, 6, 8] if len(assets_all) >= 9 else list(range(len(assets_all)))
    idx = [i for i in keep if i < len(assets_all)]

    def col(runs, key, i):
        vals = [r["per_asset"][i][key] for r in runs if i < len(r["per_asset"])]
        return float(np.mean(vals)) if vals else np.nan

    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Out-of-domain evaluation. A network trained on prices in $[20,30]$ is "
        "evaluated at each instrument's realised price level. Its local price sensitivity "
        "$|\\partial V/\\partial S|$ falls monotonically with price, because the network "
        "saturates further outside its training domain; any threshold applied to that gradient "
        "inherits the ordering. Mapping the input into the training domain removes the "
        "dependence. Five of the nine instruments are shown, evenly spaced in price; the rank "
        "correlation is over all nine.}",
        "\\label{tab:ood}",
        "\\small",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Asset & price & $|\\partial V/\\partial S|$ raw & rescaled \\\\",
        "\\midrule",
    ]
    for i in idx:
        price = un[0]["per_asset"][i]["mean_price"]
        u = col(un, "grad_abs_mean", i)
        r = col(rs, "grad_abs_mean", i) if rs else np.nan
        lines.append(f"{assets_all[i]} & {price:.0f} & {u:.3e} & {r:.3e} \\\\")
    if rs:
        sp_u = np.nanmean([r.get("spearman_price_vs_abs_grad", np.nan) for r in un])
        sp_r = np.nanmean([r.get("spearman_price_vs_abs_grad", np.nan) for r in rs])
        lines.append(f"\\midrule\n\\multicolumn{{4}}{{l}}{{\\emph{{Spearman(price, "
                     f"$|\\partial V/\\partial S|$):}} raw ${sp_u:+.2f}$, "
                     f"rescaled ${sp_r:+.2f}$}} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_ood.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_ood.tex")


def tab_ablation(d) -> None:
    """Defect ablation, trimmed to the configurations that carry the argument.

    D2, D5 and D6 are reported in the text instead: D2 moves no metric materially, and D5/D6
    move the return by a few percentage points, so a row each does not earn the space in a
    six-page paper.
    """
    if not d:
        return
    runs = d.get("runs", [])
    if not runs:
        return
    present = {r["config"] for r in runs}
    want = ["as_published", "fix_D1_ordering", "fix_D3_control_law",
            "fix_D7_annualization", "fix_D8_input_scaling", "all_fixed"]
    order = [k for k in want if k in present]
    # Keep any unexpected configuration so a renamed run is never silently dropped.
    order += [k for k in sorted(present) if k not in order and k not in (
        "fix_D2_same_bar_leak", "fix_D3_control_sign", "fix_D4_dollar_scaling",
        "fix_D5_position_integration", "fix_D6_cost_units")]
    label = {
        "as_published": "As published",
        "fix_D1_ordering": "D1 chronological order",
        "fix_D3_control_law": "D3+D4 control law",
        "fix_D3_control_sign": "D3+D4 control law",
        "fix_D7_annualization": "D7 annualisation",
        "fix_D8_input_scaling": "D8 input scaling",
        "all_fixed": "All defects fixed",
    }
    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Defect ablation on the out-of-sample window, averaged over nine instruments "
        "and three seeds. Each row fixes exactly one defect relative to the as-published "
        "configuration. D2 (same-bar leak) moves no metric materially; D5 (position "
        "integration) and D6 (cost units) change the return by a few percentage points and are "
        "reported in the text.}",
        "\\label{tab:ablation}",
        "\\small",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Configuration & return & Sharpe & ann.\\ vol & $|$pos$|$ \\\\",
        "\\midrule",
    ]
    for cfg in order:
        sel = [r["agg"] for r in runs if r["config"] == cfg]
        if not sel:
            continue
        g = lambda k: float(np.mean([s.get(k, np.nan) for s in sel]))
        bold = cfg in ("as_published", "all_fixed")
        fn = (lambda s: f"\\textbf{{{s}}}") if bold else (lambda s: s)
        lines.append(
            f"{fn(label.get(cfg,cfg))} & {fn(_fmt(g('total_return'),2,pct=True,signed=True))} & "
            f"{fn(_fmt(g('sharpe_ratio'),2,signed=True))} & "
            f"{fn(_fmt(g('annualized_volatility'),2,pct=True))} & "
            f"{fn(_fmt(g('mean_abs_position'),4))} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_ablation.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_ablation.tex")


def tab_crossover(dim, grid) -> None:
    """The accuracy-matched comparison: the paper's central table."""
    if not dim or not grid:
        return
    runs = [r for r in dim["runs"] if r.get("feasible")]
    dims = sorted({r["p"] for r in runs})
    summary = grid.get("summary", {})

    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Accuracy-matched comparison. The grid scheme is run at the smallest "
        "resolution reaching value $R^2 \\ge 0.9999$ at each dimension (found in a separate "
        "refinement study), so the two families are compared at equal accuracy rather than "
        "equal resolution. The mesh-free solver's cost is nearly flat in $p$, but its "
        "accuracy collapses once $p \\ge 4$, so it only becomes the faster option at a "
        "dimension where it no longer solves the problem.}",
        "\\label{tab:crossover}",
        "\\small",
        "\\begin{tabular}{rrrrrr}",
        "\\toprule",
        " & \\multicolumn{2}{c}{grid ($N^\\star$)} & & \\multicolumn{2}{c}{PINN} \\\\",
        "\\cmidrule(lr){2-3} \\cmidrule(lr){5-6}",
        "$p$ & $N^\\star$ & time (s) & $R^2$ & time (s) & $R^2$ \\\\",
        "\\midrule",
    ]
    for p in dims:
        g = summary.get(str(p)) or summary.get(p)
        pin = [r for r in runs if r["method"] == "PINN" and r["p"] == p]
        pin_t = _mean_sd([r.get("solve_time_s") for r in pin], 1)
        pin_r2 = _mean_sd([r.get("value_r2") for r in pin], 4)
        if g and g.get("N_star"):
            gt, gr2, ns = f"{g['time_s']:.3f}", f"{g['value_r2']:.5f}", str(g["N_star"])
        else:
            gt, gr2, ns = "--", "--", "--"
        # Flag whether the PINN is both faster and accurate at this dimension.
        mark = ""
        if pin and g and g.get("N_star"):
            pin_mean_r2 = float(np.mean([r["value_r2"] for r in pin]))
            pin_mean_t = float(np.mean([r["solve_time_s"] for r in pin]))
            if pin_mean_r2 > 0.99:
                mark = "$\\dagger$" if pin_mean_t < g["time_s"] else ""
            else:
                mark = "$\\ast$"
        lines.append(f"{p} & {ns} & {gt} & {gr2} & {pin_t}{mark} & {pin_r2} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\vspace{2pt}",
        "\\\\ {\\footnotesize $\\ast$ PINN accuracy has collapsed ($R^2<0$); $\\dagger$ PINN "
        "is both faster and accurate.}",
        "\\end{table}",
        "",
    ]
    (TABDIR / "tab_crossover.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_crossover.tex")


def tab_grid(d, target_r2=0.9999) -> None:
    """Grid-refinement detail: accuracy versus resolution, for the appendix or main text."""
    if not d:
        return
    runs = [r for r in d["runs"] if r.get("value_r2") is not None]
    dims = sorted({r["p"] for r in runs})
    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Grid refinement of the finite-difference solver. $N^\\star$ is the "
        "smallest resolution reaching $R^2 \\ge 0.9999$. Cost grows far faster than the "
        "point count $N^p$ alone, because the explicit time step is CFL-limited by the mesh "
        "spacing.}",
        "\\label{tab:grid}",
        "\\small",
        "\\begin{tabular}{rrrrr}",
        "\\toprule",
        "$p$ & $N$ & grid points & time (s) & $R^2$ \\\\",
        "\\midrule",
    ]
    for p in dims:
        rows = sorted([r for r in runs if r["p"] == p], key=lambda r: r["N"])
        star = next((r["N"] for r in rows if r["value_r2"] >= target_r2), None)
        for r in rows:
            nm = f"{r['N']}$^\\star$" if r["N"] == star else str(r["N"])
            pp = str(p) if r is rows[0] else ""
            lines.append(f"{pp} & {nm} & {r['n_grid_points']} & "
                         f"{r['solve_time_s']:.3f} & {r['value_r2']:.5f} \\\\")
        lines.append("\\midrule")
    if lines[-1] == "\\midrule":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_grid.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_grid.tex")


def tab_latency(d) -> None:
    """Post-solve evaluation latency, separating solve cost from run-time cost."""
    if not d:
        return
    runs = d.get("runs", [])
    if not runs:
        return

    def get(prefix: str, p: int, batch: int, device: str | None = None):
        for r in runs:
            if (r["method"].startswith(prefix) and r["p"] == p and r["batch"] == batch
                    and (device is None or r["device"] == device)):
                return r
        return None

    dims = sorted({r["p"] for r in runs})
    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Post-solve evaluation latency in microseconds per state, once a solution "
        "exists. \\emph{Control} includes the gradient required by $u^\\star$; the grid value "
        "row is interpolation only, shown for reference. A day is 390 minute decisions. "
        "Neither method constrains latency at this frequency, and single-state evaluation is "
        "faster on the CPU than the GPU for the neural solver because it is launch-bound "
        "rather than compute-bound.}",
        "\\label{tab:latency}",
        "\\small",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "Method & device & $p$ & 1 state & 390 states \\\\",
        "\\midrule",
    ]
    for p in dims:
        for method, dev, device_key, row in (
            ("PINN", "GPU", "cuda", get("PINN", p, 1, "cuda")),
            ("PINN", "CPU", "cpu", get("PINN", p, 1, "cpu")),
            ("grid (control)", "CPU", None, get("Finite Difference", p, 1)),
        ):
            if row is None:
                continue
            key = "us_per_state_control" if device_key is None else "us_per_state"
            big_key = key
            if device_key is None:
                big = get("Finite Difference", p, 390)
            else:
                big = get("PINN", p, 390, device_key)
            b = f"{big[big_key]:.2f}" if big else "--"
            lines.append(f"{method} & {dev} & {p} & {row[key]:.1f} & {b} \\\\")
        lines.append("\\midrule")
    if lines[-1] == "\\midrule":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_latency.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_latency.tex")


def tab_highdim(d) -> None:
    """Accuracy versus dimension beyond the range where grid methods are runnable."""
    if not d:
        return
    runs = d.get("runs", [])
    if not runs:
        return
    dims = sorted({r["p"] for r in runs})
    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Accuracy against the closed-form solution at dimensions where grid methods are "
        "no longer runnable. The problem is non-separable (per-asset heterogeneous risk and "
        "impact, random off-diagonal risk), so $V$ is a genuinely $p$-dimensional quadratic. The "
        "grid baseline exists only to $p=5$; beyond that the analytic reference is the only way "
        "to score the neural solver, which is exactly the situation a practitioner would face.}",
        "\\label{tab:highdim}",
        "\\small",
        "\\begin{tabular}{rrrr}",
        "\\toprule",
        "$p$ & PINN $R^2$ & time (s) & grid $R^2$ \\\\",
        "\\midrule",
    ]
    for p in dims:
        pin = [r for r in runs if r.get("method") == "PINN" and r.get("p") == p
               and r.get("hetero") is True and r.get("feasible")]
        grd = [r for r in runs if r.get("method") == "Finite Difference" and r.get("p") == p
               and r.get("feasible")]
        if not pin:
            continue
        r2 = [r["value_r2"] for r in pin]
        sd = float(np.std(r2, ddof=1)) if len(r2) > 1 else 0.0
        # Suppress a sd that rounds to zero; it is noise, and the "+/- 0.0000" costs the
        # column more width than it is worth.
        r2s = f"{np.mean(r2):+.4f}"
        if len(r2) > 1 and sd >= 5e-5:
            r2s += f" $\\pm$ {sd:.4f}"
        t = float(np.mean([r["solve_time_s"] for r in pin]))
        g = f"{grd[0]['value_r2']:+.5f}" if grd else "n/a$^\\dagger$"
        lines.append(f"{p} & {r2s} & {t:.0f} & {g} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\\\[2pt] {\\footnotesize $^\\dagger$not runnable: $N^p$ grid points at the "
        "resolution needed for the accuracy target.}",
        "\\end{table}",
        "",
    ]
    (TABDIR / "tab_highdim.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_highdim.tex")


def tab_control(order, floor, p5) -> None:
    """Control accuracy versus value accuracy, and which refinement each responds to.

    The paper's central table. Three panels:
      (a) both errors against the closed-form reference, with the observed order of the control
          error and the ratio between the two errors;
      (b) the time-refinement experiment -- mesh fixed, only the snapshot count changed -- which
          is what separates a value error limited by time from a control error limited by space;
      (c) the ratio's growth as the mesh is refined, which is the form in which the result bears
          on cost.
    """
    rows_a = [r for r in (order or {}).get("part_c_orders_at_best_probe", [])]
    if not rows_a:
        print("  NOTE: no exp_control_order results; skipping tab_control")
        return

    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        # Single column again: the ratio sequences are now summarised as first -> peak, which
        # brings the table back inside one column's width.
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Value accuracy is not control accuracy. The control is the deliverable of an "
        "HJB and is a derivative of the value function, so the two errors need not track each "
        "other. Both errors are relative $L^2$ norms ($\\|a-a^{\\star}\\|_2/\\|a^{\\star}\\|_2$) and "
        "every order in this table is the least-squares slope of $\\log$(error) against "
        "$\\log h$. \\emph{Top}: both errors against the closed-form reference, with the observed "
        "order of the control error. \\emph{Middle}: with the mesh fixed and only the number of "
        "stored snapshots changed, the value error falls by up to two orders of magnitude while "
        "the control error improves by at most a factor of about $23$ and then plateaus -- the "
        "two are limited by different refinements. \\emph{Bottom}: for each sweep, the "
        "least-squares control order with its fit quality, and the control/value error ratio "
        "from its first to its largest value. The order is the robust statement; the ratio is a "
        "ratio of two convergences and turns over wherever the value error regresses, so it is "
        "summarised rather than printed in full. The fourth row shows what happens when the "
        "solver's snapshot memory cap silently coarsens the time resolution as $N^5$ grows -- "
        "the fit degenerates and the order is meaningless -- and the last row reruns $p=5$ with "
        "the cap raised so the time resolution is held fixed (Section~\\ref{sec:control}).}",
        "\\label{tab:control}",
        "\\scriptsize",
        "\\begin{tabular}{rlrrrr}",
        "\\toprule",
        "$p$ & $N$ & value err & ctrl err & ord(ctrl) & ratio \\\\",
        "\\midrule",
    ]
    for r in sorted(rows_a, key=lambda r: (r["p"], r["N"])):
        # Stored as a normalised MSE; the paper's metric is its square root, and the per-step
        # order stored alongside it was fitted to the square, so it halves.
        oc = order_from_mse_order(r.get("order_control", float("nan")))
        ocs = f"{oc:.2f}" if oc == oc else "--"
        lines.append(f"{r['p']} & {r['N']} & {rms_from_mse(r['value_err']):.2e} & "
                     f"{rms_from_mse(r['control_err']):.2e} & "
                     f"{ocs} & {ratio_from_mse_ratio(r['ratio']):.1f} \\\\")

    fl = (floor or {}).get("part_d_snapshot_sweep", [])
    if fl:
        lines.append("\\midrule")
        lines.append("\\multicolumn{6}{l}{\\emph{time refinement only, mesh fixed}} \\\\")
        for p in sorted({r["p"] for r in fl}):
            for N in sorted({r["N"] for r in fl if r["p"] == p}):
                rs = sorted([r for r in fl if r["p"] == p and r["N"] == N],
                            key=lambda r: r["n_snap"])
                if len(rs) < 2:
                    continue
                vg = ratio_from_mse_ratio(rs[0]["value_err"] / rs[-1]["value_err"])
                cg = ratio_from_mse_ratio(rs[0]["control_err"] / rs[-1]["control_err"])
                lines.append(f"{p} & {N} & $\\times{vg:.1f}$ & $\\times{cg:.1f}$ & -- & "
                             f"{ratio_from_mse_ratio(rs[-1]['ratio']):.1f} \\\\")

    lines.append("\\midrule")
    lines.append("\\multicolumn{6}{l}{\\emph{fitted control order and ratio growth}} \\\\")
    # The fitted order is the robust result and is reported for every sweep. The ratio is
    # summarised as first -> peak rather than as a full sequence: the sequences are long, they
    # break wherever the value error regresses, and spelling them out made the table 112 pt too
    # wide for one column while adding little. The full sequences are in the reproduction; the
    # text states which dimensions stay monotone and where the others turn over.
    fits = {}
    fit_path = RESULTS / "exp_control_orders_fit.json"
    if fit_path.exists():
        try:
            for k, v in (json.loads(fit_path.read_text()).get("fits") or {}).items():
                src, _, ptok = k.partition("|p=")
                fits[(src, int(ptok))] = v
        except Exception as e:
            print(f"  NOTE: could not read fitted orders ({e}); omitting them")

    def emit(rows, label, fit_key=None):
        rs = sorted(rows, key=lambda r: r["N"])
        if len(rs) < 2:
            return
        ratios = [ratio_from_mse_ratio(r["ratio"]) for r in rs]
        first, peak = ratios[0], max(ratios)
        fit = fits.get(fit_key) if fit_key else None
        bits = [label + ":"]
        if fit:
            bits.append(f"order ${order_from_mse_order(fit['control_order']):.2f}$ "
                        f"($R^2={fit['control_fit_r2']:.3f}$),")
        bits.append(f"ratio ${first:.1f} \\to {peak:.1f}$")
        lines.append("\\multicolumn{6}{l}{" + " ".join(bits) + "} \\\\")

    for p in sorted({r["p"] for r in rows_a}):
        emit([r for r in rows_a if r["p"] == p], f"$p={p}$",
             ("exp_control_order part_c", p))
    for p in sorted({r["p"] for r in (floor or {}).get("part_e_high_dimension", [])}):
        # The p=5 row here used the solver's default snapshot cap, which silently coarsened the
        # time resolution as N^5 grew; its fit R^2 exposes that, and the row below reruns it
        # properly. Label it so the two are not confused.
        lab = f"$p={p}$" + (" (cap coarsened time)" if p == 5 else "")
        emit([r for r in floor["part_e_high_dimension"] if r["p"] == p], lab,
             ("exp_control_floor part_e", p))
    if p5 and p5.get("part_g_refinement"):
        emit(p5["part_g_refinement"], "$p=5$, time held fixed",
             ("exp_control_p5 part_g", 5))

    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_control.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_control.tex")


def tab_extract(ext, extp3, extp5, merton=None, intrinsic=None) -> None:
    """Gradient-extraction order for three reconstructions, on functions of known form.

    This is the table behind the paper's central claim. The functions are synthetic, so the
    orders are properties of the reconstruction rather than of the benchmark -- which matters,
    because the benchmark's own value function is quadratic and a cubic reconstruction reproduces
    quadratics exactly, flattering that method. The non-polynomial rows are the ones to quote, and
    the last column is the Merton value function, which is a power function from a real
    non-linear control problem rather than a synthetic test case.

    ORDERS ARE CONVERGENCE ORDERS, NOT SLOPES OF A SQUARED ERROR. The experiment stores a
    normalised MSE and fits log(MSE) against log(h), which doubles the slope; `metrics.py` undoes
    that. The last row is the same measurement with the probe step taken far below the mesh --
    which is what separates the order of the RECONSTRUCTION from the order actually achieved by a
    fixed-relative probe, and is why the two order tables in this paper no longer disagree.
    """
    by_fn: dict[str, dict[str, dict]] = {}
    for src in (ext, extp3, extp5):
        for r in (src or {}).get("synthetic", []):
            by_fn.setdefault(r["function"], {}).update(r.get("orders") or {})

    # The Merton orders live in a different shape: one non-polynomial value function, three
    # extractors, in meta.exact_node_orders.
    m_orders = ((merton or {}).get("meta") or {}).get("exact_node_orders") or {}

    # Same three extractors, same functions, probe step far below the mesh: the reconstruction's
    # own order, with the probe no longer the limiter.
    intr: dict[str, dict[str, float]] = {}
    for r in (intrinsic or {}).get("synthetic", []) or []:
        for method, track in (r.get("tracks") or {}).items():
            pts = [(h, e) for h, e in track if e and e > FLOOR_FOR_ORDER]
            if len(pts) < 3:
                continue
            order_rms, _ = fit_order([p[0] for p in pts],
                                     [rms_from_mse(p[1]) for p in pts])
            intr.setdefault(r["function"], {})[method] = order_rms

    if not by_fn and not m_orders:
        print("  NOTE: no extraction results; skipping tab_extract")
        return

    # Pool the orders across every dimension that was run, and report the range rather than one
    # value: the point of the synthetic test is that the order is a property of the
    # reconstruction, so agreement across p=2, 3 and 5 is part of the evidence.
    pooled: dict[tuple[str, str], list[float]] = {}
    for src in (ext, extp3, extp5):
        for r in (src or {}).get("synthetic", []):
            for key, v in (r.get("orders") or {}).items():
                if v and v.get("order") is not None:
                    pooled.setdefault((key, r["function"]), []).append(
                        order_from_mse_order(v["order"]))
    n_dims = sum(1 for s in (ext, extp3, extp5) if (s or {}).get("synthetic"))

    # Keep a stable, meaningful order: the benchmark's case first, then the general ones, and the
    # Merton power function last because it comes from an actual non-linear control problem.
    # Headings are abbreviated so the table fits one column of a two-column layout.
    display = {"quadratic": "quad.", "quartic": "quartic", "exponential": "exp.",
               "trigonometric": "trig."}
    preferred = ["quadratic", "quartic", "exponential", "trigonometric"]
    functions = [f for f in preferred if f in by_fn] + \
                [f for f in by_fn if f not in preferred]
    if m_orders:
        functions.append("Merton")

    methods = [("fd", "multilinear $+$ probe"),
               ("cell", "multilinear, slope"),
               ("spline", "cubic $+$ probe")]

    # Spread across dimensions, for the caption: the range is evidence but too wide to print in
    # six columns, so the table carries the mean and the caption reports the spread.
    spreads = []
    for vals in pooled.values():
        if len(vals) > 1:
            spreads.append(max(vals) - min(vals))
    spread_txt = (f" Orders agreed across dimensions to within {max(spreads):.1f}"
                  if spreads else "")

    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{The order of the reconstruction governs control accuracy, not the accuracy of "
        "the solution. Each row turns nodal values into a gradient a different way: a "
        "piecewise-linear (order-one) reconstruction whose gradient is probed by finite "
        "differences, that same reconstruction differentiated exactly, and a cubic (order-three) "
        "reconstruction probed exactly as the first. The columns report the convergence rate of "
        "the \\emph{gradient} --- the control --- measured on functions whose gradients are known "
        "exactly, so the rates are properties of the reconstruction rather than of the benchmark; "
        "the first four columns are this paper's own problem, averaged over "
        f"$p = 2, 3$ and $5$.{spread_txt}. Every order is fitted to the relative $L^2$ error, "
        "and the probe step is stated because it is not innocent: the first three rows use the "
        "practical probe $\\varepsilon = h/4$, and the last row repeats the same three "
        "measurements with $\\varepsilon$ far below the mesh, which recovers the reconstruction's "
        "own order --- the cubic reaches $\\approx 3.5$ there, so a probe that is not scaled with "
        "the mesh silently caps the order a high-order reconstruction can deliver. The last "
        "column is the Merton value function, a power function from a genuinely non-linear "
        "control problem --- non-polynomial, so the cubic reconstruction is not exact there. "
        "Differentiating the piecewise-linear reconstruction exactly is no better than probing "
        "it, so consistency with the interpolant buys nothing. The quadratic column is this "
        "paper's own case and flatters the cubic method, which reproduces quadratics exactly; "
        "every other column is the one to quote.}",
        "\\label{tab:extract}",
        "\\small",
        # Two extra rows went in with the intrinsic-probe measurement, and the row labels are the
        # widest thing in this table; the inter-column space is tightened rather than the font
        # shrunk, so the numbers stay the same size as every other table's.
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{l" + "r" * len(functions) + "}",
        "\\toprule",
        " & \\multicolumn{" + str(len(functions)) + "}{c}{gradient-error convergence rate} \\\\",
        "\\cmidrule(lr){2-" + str(len(functions) + 1) + "}",
        "reconstruction & " + " & ".join(display.get(f, f) for f in functions) + " \\\\",
        "\\midrule",
    ]
    for key, label in methods:
        cells = []
        for f in functions:
            if f == "Merton":
                v = m_orders.get(key) or {}
                o = v.get("order")
                cells.append("exact" if o is None else f"{order_from_mse_order(o):.1f}")
                continue
            vals = pooled.get((key, f), [])
            if not vals:
                # No finite order means the extractor was already at machine precision, which is
                # what happens when the basis reproduces that function exactly.
                cells.append("exact")
            else:
                cells.append(f"{sum(vals)/len(vals):.1f}")
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    if intr:
        def _cell(fname: str, method: str) -> str:
            v = (intr.get(fname) or {}).get(method)
            return f"{v:.1f}" if isinstance(v, float) and v == v else "--"

        lines.append("\\midrule")
        lines.append("multilinear, $\\varepsilon \\ll h$ & "
                     + " & ".join("--" if f == "Merton" else _cell(f, "fd")
                                  for f in functions) + " \\\\")
        lines.append("cubic, $\\varepsilon \\ll h$ & "
                     + " & ".join("--" if f == "Merton" else _cell(f, "spline")
                                  for f in functions) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_extract.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_extract.tex")


def tab_limit(res) -> None:
    """Order against monotonicity: what a limited reconstruction costs and what it buys.

    Generated from `exp_limited_reconstruction.py`. The two columns that matter for a control are
    the wrong-way fraction (the reconstruction pointing OPPOSITE to a significant true gradient --
    for a derivative that is a trade in the wrong direction) and the overshoot beyond the largest
    true gradient. The order column is reported only where an order exists: a discontinuous
    gradient and noisy nodal values have none.
    """
    fns = (res or {}).get("functions") or {}
    if not fns:
        print("  NOTE: no exp_limited_reconstruction results; skipping tab_limit")
        return
    rows = [
        ("smooth, monotone", "exponential", "order"),
        ("smooth, interior turning point", "trigonometric", "order"),
        ("gradient kink", "kink", None),
        ("2\\% nodal noise (solved grid)", "exponential_noisy", None),
    ]
    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Order against monotonicity, on functions whose gradients are known. "
        "\\emph{cubic} is the unlimited reconstruction of Proposition~1 with a probe far below the "
        "mesh; \\emph{limited} is the same gradient passed through a monotonised-central limiter "
        "built from the nodal one-sided slopes. \\emph{Wrong way} is the fraction of samples where "
        "the reconstruction has the OPPOSITE sign to a significant true gradient --- for a control, "
        "which is a derivative, that is a trade in the wrong direction rather than a small error, "
        "and returning zero at a turning point is the safe answer and is not counted. "
        "\\emph{Overshoot} is the largest recovered gradient relative to the largest true one. The "
        "order column is given only where an order exists: a discontinuous gradient and noisy data "
        "have none. On smooth data the limiter is inert (no wrong-way samples either way) and costs "
        "nothing except at interior turning points, where clipping drops it from $3.7$ to $1.5$. On "
        "data that are not smooth it is what stops the control pointing the wrong way.}",
        "\\label{tab:limit}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        " & \\multicolumn{2}{c}{wrong way (\\%)} & \\multicolumn{2}{c}{overshoot ($\\times$)} \\\\",
        "\\cmidrule(lr){2-3} \\cmidrule(lr){4-5}",
        "data condition & cubic & limited & cubic & limited \\\\",
        "\\midrule",
    ]
    for label, key, _ in rows:
        pm = (fns.get(key) or {}).get("per_method") or {}
        if not pm:
            continue
        c, l = pm.get("cubic") or {}, pm.get("limited") or {}
        lines.append(
            f"{label} & {100*c.get('max_wrong_way', float('nan')):.1f} & "
            f"{100*l.get('max_wrong_way', float('nan')):.1f} & "
            f"{c.get('max_overshoot', float('nan')):.2f} & "
            f"{l.get('max_overshoot', float('nan')):.2f} \\\\")
    lines += [
        "\\midrule",
        "\\multicolumn{5}{l}{\\emph{convergence order, where one exists}} \\\\",
    ]
    for label, key, _ in rows:
        pm = (fns.get(key) or {}).get("per_method") or {}
        c, l = pm.get("cubic") or {}, pm.get("limited") or {}
        # Noisy nodal values have no convergence order -- the noise floor sets the error -- so the
        # fitted slope (which comes out negative) is not reported as one.
        if c.get("order") is None or "noisy" in key:
            continue
        lines.append(f"\\multicolumn{{5}}{{l}}{{{label}: cubic ${c['order']:.2f}$, "
                     f"limited ${l['order']:.2f}$}} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_limit.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_limit.tex")


