def tab_accuracy(d) -> None:
    if not d:
        return
    runs = [r for r in d["runs"] if r.get("feasible")]
    dims = sorted({r["p"] for r in runs})
    rows = []
    for method in METHOD_ORDER:
        for p in dims:
            sel = [r for r in runs if r["method"] == method and r["p"] == p]
            if not sel:
                rows.append((method, p, "--", "--", "--", "--"))
                continue
            rows.append((
                method, p,
                _mean_sd([r.get("value_r2") for r in sel], 5),
                _mean_sd([r.get("value_mse") for r in sel], 8),
                _mean_sd([r.get("control_r2") for r in sel], 4),
                _mean_sd([r.get("control_sign_agreement") for r in sel], 3),
            ))

    lines = [
        "% Auto-generated by src/make_tables.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Accuracy against the closed-form Riccati solution, by state dimension "
        "$p$. $R^2$ is computed on the value function and on the optimal control, each "
        "averaged over eight time slices; sign agreement is the fraction of sampled states "
        "where the control has the same sign as the analytic optimum. PINN entries are "
        "mean $\\pm$ s.d. over seeds.}",
        "\\label{tab:accuracy}",
        "\\small",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "Method & $p$ & value $R^2$ & value MSE & control $R^2$ & sign agr. \\\\",
        "\\midrule",
    ]
    prev = None
    for method, p, r2, mse, cr2, sa in rows:
        m = method if method != prev else ""
        prev = method
        lines.append(f"{m} & {p} & {r2} & {mse} & {cr2} & {sa} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABDIR / "tab_accuracy.tex").write_text("\n".join(lines))
    print("  wrote paper/tables/tab_accuracy.tex")


