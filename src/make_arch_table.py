"""
LaTeX table for the architecture-sensitivity sweep, generated from the measurement file.

Exists so the paper can answer the objection every solver benchmark attracts -- "you tested one
architecture, so the boundary may be a property of that architecture" -- with a measurement instead
of the current limitation note. The manuscript said `no architecture search is performed`, which was
true when written; this table makes it false, so the sentence had to be rewritten alongside it.

The grid row is included deliberately, as a reference point rather than as another architecture: the
claim being tested is whether the neural family can be rescued, and the reader needs to know what it
is being rescued TOWARD.

Usage: python src/make_arch_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parent.parent / "results"
TABDIR = Path(__file__).resolve().parent.parent / "paper" / "tables"

# Readable labels for the (hidden, layers) pairs the sweep used. Kept short deliberately: the table
# has six columns in a two-column layout and the labels were the second-cheapest thing to shorten
# after the inter-column space.
LABEL = {
    (64, 4): "4x64 (paper)",
    (64, 2): "2x64 shallow",
    (64, 8): "8x64 deep",
    (128, 4): "4x128 wide",
    (256, 6): "6x256 both",
}


def main() -> int:
    path = RESULTS / "exp_arch_ablation.json"
    if not path.exists():
        print(f"missing {path}; run exp_arch_ablation.py first")
        return 1
    d = json.loads(path.read_text(encoding="utf-8"))
    rows = d["rows"]
    grid = d["grid"]
    p = d["p"]
    epochs = sorted({r["epochs"] for r in rows})

    lines = [
        "% Auto-generated by src/make_arch_table.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Architecture sensitivity at $p=" + str(p) + "$, the dimension where the fixed "
        "budget collapses. Every row is a full solve scored against the analytic reference; the "
        "first row is the accuracy-matched grid scheme at the same dimension, for scale. Two "
        "separate questions are answered here. Does more capacity help at a fixed budget -- yes, "
        "decisively: at " + f"{epochs[0]:,}" + " epochs the paper's $4\\times64$ scores $R^2=-3.28$ "
        "while an $8\\times64$ MLP, using $2.3\\times$ the parameters, scores $+0.9953$. And is "
        "capacity the only lever -- no: raising the budget of the ORIGINAL architecture to "
        f"{epochs[-1]:,}" + " epochs reaches $+0.9972$ for less wall time than the largest network "
        "here. Both routes succeed, and both remain slower and less accurate than the grid scheme.}",
        "\\label{tab:arch}",
        "\\small",
        # 3 pt, not 4: the first version of this table measured 277.42 pt against a 252.0 pt column,
        # a 25 pt overflow that LaTeX reported as 19 pt once the float had absorbed part of it. Six
        # columns of a two-column layout have very little room, so the inter-column space is the
        # cheapest thing to spend -- but the row LABELS were shortened at the same time, because
        # paying for width with legibility is the wrong trade when the labels are three words.
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{l r r r r r}",
        "\\toprule",
        "net & ep. & params & time & value & control \\\\",
        " & & & (s) & $R^2$ & $R^2$ \\\\",
        "\\midrule",
        f"grid ($N={grid['n_grid']}$) & --- & --- & {grid['time_s']:.0f} & "
        f"${grid['value_r2']:+.5f}$ & ${grid['control_r2']:+.5f}$ \\\\",
        "\\midrule",
    ]
    for ep in epochs:
        for r in sorted([x for x in rows if x["epochs"] == ep], key=lambda x: x["params"]):
            lab = LABEL.get((r["hidden"], r["layers"]),
                            f"{r['layers']}x{r['hidden']}")
            sd = f"$\\pm{r['value_r2_sd']:.3f}$" if r.get("n_seeds", 1) > 1 else ""
            lines.append(f"{lab} & {r['epochs'] // 1000}k & {r['params']:,} & {r['time_s']:.0f} & "
                         f"${r['value_r2_mean']:+.5f}${sd} & ${r['control_r2_mean']:+.4f}$ \\\\")
        if ep != epochs[-1]:
            lines.append("\\midrule")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    out = TABDIR / "tab_arch.tex"
    TABDIR.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    for ep in epochs:
        for r in sorted([x for x in rows if x["epochs"] == ep], key=lambda x: x["params"]):
            print(f"  {ep:>6} ep  {r['layers']}x{r['hidden']:<4} {r['params']:>9,} params  "
                  f"{r['time_s']:>6.1f}s  value R2={r['value_r2_mean']:+.5f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
